"""Average temperature per station: nearly unique keys, so the combiner has
little to merge. The control job for the combiner experiments (needs a
`station` column, e.g. the data generated by eval/experiments.py)."""


def map_fn(key, row):
    yield row["station"], (float(row["temp"]), 1)    # (sum, count)


def combine_fn(key, values):
    total, count = 0.0, 0
    for s, c in values:
        total += s
        count += c
    yield key, (total, count)


def reduce_fn(key, values):
    total, count = 0.0, 0
    for s, c in values:
        total += s
        count += c
    yield key, total / count
